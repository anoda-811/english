function article(word) {
  return /^[aeiou]/i.test(word) ? "an" : "a";
}

/**
 * @param {[string, string][]} pool
 * @param {Record<string, number>} levelSizes
 * @param {string} pos
 * @param {string} prefix
 */
function buildFromPool(pool, levelSizes, pos, prefix) {
  const seen = new Set();
  /** @type {[string, string][]} */
  const unique = [];
  for (const pair of pool) {
    if (seen.has(pair[0])) continue;
    seen.add(pair[0]);
    unique.push(pair);
  }
  const needed = Object.values(levelSizes).reduce((a, b) => a + b, 0);
  if (unique.length < needed) {
    throw new Error(`${pos}: need ${needed}, have ${unique.length}`);
  }

  /** @type {object[]} */
  const words = [];
  let offset = 0;
  for (const [level, size] of Object.entries(levelSizes)) {
    const slice = unique.slice(offset, offset + size);
    offset += size;
    slice.forEach(([en, ja], i) => {
      const a = article(en);
      words.push({
        id: `${prefix}${level}-${i + 1}`,
        en,
        ja,
        pos,
        level,
        exampleEn: pos === "adjective" ? `It is ${a} ${en} thing.` : `She spoke ${en}.`,
        exampleJa: pos === "adjective" ? `???${ja}?????` : `???${ja}????`,
      });
    });
  }
  return words;
}

